const LABEL: Record<Brand, string> = {
  depop: 'Depop',
  vinted: 'Vinted',
};

function computeVerticalAlign(height: string, descentRatio: number): string {
  if (descentRatio === 0) return '0';
  const match = height.match(/^(-?\d*\.?\d+)([a-z%]+)$/);
  if (!match) return `${(-descentRatio).toFixed(3)}em`;
  const value = parseFloat(match[1]);
  const unit = match[2];
  return `${(-descentRatio * value).toFixed(3)}${unit}`;
}

export function BrandWordmark({
  brand,
  variant = 'mark',
  height = '1em',
  className = '',
}: BrandWordmarkProps) {
  const glyph = GLYPH[brand][variant];
  const verticalAlign = computeVerticalAlign(height, glyph.descentRatio);
  return (
    <span
      className={`inline-flex shrink-0 items-center ${className}`}
      style={{ verticalAlign }}
      aria-label={LABEL[brand]}
      role="img"
    >
      <svg
        xmlns="http://www.w3.org/2000/svg"
        viewBox={glyph.viewBox}
        fill={glyph.fill}
        style={{ height, width: 'auto' }}
        aria-hidden
        focusable="false"
      >
        {glyph.d}
      </svg>
    </span>
  );
}
